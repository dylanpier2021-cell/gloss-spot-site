function post(url, body, retry) {
  const go = () => fetch(url, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) })
    .then((r) => r.json().catch(() => ({})).then((j) => { if (!r.ok) { const e = new Error("http " + r.status); e.status = r.status; e.body = j; throw e; } return j; }));
  return retry ? go().catch((e) => (e.status && e.status < 500 ? Promise.reject(e) : new Promise((ok) => setTimeout(ok, 1500)).then(go))) : go();
}
