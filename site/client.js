// Browser script → output/assets/site.js. Prices are injected from content.js
// so the booking widget, calculator and price cards can never disagree.
export function clientJS(data) {
  return `/* The Gloss Spot — generated by site/build.js. Edit site/client.js. */
window.GS = ${JSON.stringify(data)};
` + String.raw`
(function () {
  "use strict";
  var GS = window.GS;
  var $ = function (s, r) { return (r || document).querySelector(s); };
  var $$ = function (s, r) { return Array.prototype.slice.call((r || document).querySelectorAll(s)); };
  var money = function (n) { return "$" + Number(n).toLocaleString("en-US"); };
  var reduce = window.matchMedia && matchMedia("(prefers-reduced-motion: reduce)").matches;
  var saveData = navigator.connection && (navigator.connection.saveData || /2g/.test(navigator.connection.effectiveType || ""));

  // ── header + drawer ──
  var hdr = $("[data-hdr]");
  var onScroll = function () { if (hdr) hdr.classList.toggle("solid", window.scrollY > 40); };
  window.addEventListener("scroll", onScroll, { passive: true }); onScroll();
  var mb = $("[data-menu]"), dr = $("[data-drawer]");
  if (mb && dr) {
    mb.addEventListener("click", function () {
      var open = dr.hasAttribute("hidden");
      if (open) dr.removeAttribute("hidden"); else dr.setAttribute("hidden", "");
      mb.setAttribute("aria-expanded", String(open));
      hdr.classList.add("solid");
    });
    dr.addEventListener("click", function (e) { if (e.target.closest("a")) { dr.setAttribute("hidden", ""); mb.setAttribute("aria-expanded", "false"); } });
  }

  // ── reveal on scroll ──
  var reveals = $$(".reveal");
  if ("IntersectionObserver" in window && !reduce) {
    var ro = new IntersectionObserver(function (es) {
      es.forEach(function (e) { if (e.isIntersecting) { e.target.classList.add("in"); ro.unobserve(e.target); } });
    }, { rootMargin: "0px 0px -8% 0px" });
    reveals.forEach(function (el) { ro.observe(el); });
  } else reveals.forEach(function (el) { el.classList.add("in"); });

  // ── background videos (OpenArt loops from our real photos) ──
  function startVideo(v) {
    var mobile = window.innerWidth < 760;
    var src = (mobile && v.dataset.srcMobile) || v.dataset.src;
    if (!src || v.dataset.loaded) return;
    v.dataset.loaded = "1";
    v.src = src;
    v.addEventListener("playing", function () { v.classList.add("on"); }, { once: true });
    var p = v.play(); if (p && p.catch) p.catch(function () {});
  }
  var vids = $$("video[data-src]");
  if (!reduce && !saveData && vids.length) {
    var hv = vids.filter(function (v) { return v.classList.contains("bgv-hero"); });
    var rest = vids.filter(function (v) { return !v.classList.contains("bgv-hero"); });
    // Hero video only after the page (and its photo) has fully loaded.
    var afterLoad = function () { setTimeout(function () { hv.forEach(startVideo); }, 600); };
    if (document.readyState === "complete") afterLoad(); else window.addEventListener("load", afterLoad);
    if ("IntersectionObserver" in window) {
      var vo = new IntersectionObserver(function (es) {
        es.forEach(function (e) {
          var v = e.target;
          if (e.isIntersecting) { startVideo(v); if (v.paused && v.dataset.loaded) v.play().catch(function () {}); }
          else if (!v.paused) v.pause();
        });
      }, { rootMargin: "200px" });
      rest.forEach(function (v) { vo.observe(v); });
    }
  }

  // ── Instagram embeds: load Instagram's script only when the grid is near ──
  var ig = $("[data-ig]");
  if (ig) {
    var loadIg = function () {
      if (window.instgrm) return window.instgrm.Embeds.process();
      var s = document.createElement("script"); s.async = true; s.src = "https://www.instagram.com/embed.js"; document.body.appendChild(s);
    };
    if ("IntersectionObserver" in window) {
      var io = new IntersectionObserver(function (es) { if (es[0].isIntersecting) { io.disconnect(); loadIg(); } }, { rootMargin: "600px" });
      io.observe(ig);
    } else loadIg();
  }

  // ── before/after sliders ──
  $$(".ba-range").forEach(function (r) {
    r.addEventListener("input", function () { r.parentNode.style.setProperty("--pos", r.value + "%"); });
  });

  // ── booking widget ──
  var bk = $("[data-booking]");
  var S = { svc: null, tier: null, size: null, twoStep: false, day: null, slot: null, slots: null };
  function pkg(k) { for (var i = 0; i < GS.packages.length; i++) if (GS.packages[i].key === k) return GS.packages[i]; return null; }
  function svcName() {
    if (S.svc === "ceramic") return "Ceramic Coating" + (S.tier != null ? " (" + GS.ceramic.tiers[S.tier] + ")" : "");
    var p = pkg(S.svc); return p ? p.name + (S.svc === "lux" && S.twoStep ? " + two-step" : "") : "";
  }
  function sizeLabels() { return S.svc === "ceramic" ? GS.ceramicSizes : GS.sizes; }
  function price() {
    if (S.size == null || !S.svc) return null;
    if (S.svc === "ceramic") return S.tier == null ? null : GS.ceramic.prices[S.size][S.tier];
    var p = pkg(S.svc); return p.prices[S.size] + (S.svc === "lux" && S.twoStep ? (p.twoStepAdd || 0) : 0);
  }
  function hours() {
    if (S.svc === "ceramic") return GS.ceramic.hours;
    var p = pkg(S.svc); return p ? p.hours[S.size == null ? 0 : S.size] : 2;
  }
  function chicagoISODate(d) {
    var f = new Intl.DateTimeFormat("en-CA", { timeZone: "America/Chicago", year: "numeric", month: "2-digit", day: "2-digit" });
    return f.format(d);
  }
  function fmtTime(iso) { return new Date(iso).toLocaleTimeString("en-US", { timeZone: "America/Chicago", hour: "numeric", minute: "2-digit" }); }
  function fmtDay(key, style) {
    var d = new Date(key + "T12:00:00Z");
    return d.toLocaleDateString("en-US", style === "long" ? { weekday: "long", month: "short", day: "numeric", timeZone: "UTC" } : { weekday: "short", timeZone: "UTC" });
  }

  function openStep(n) {
    if (!bk) return;
    $$(".bk-step", bk).forEach(function (s) {
      var k = +s.dataset.step;
      s.classList.toggle("is-open", k === n);
    });
    var st = $('.bk-step[data-step="' + n + '"]', bk);
    if (st && st.getBoundingClientRect().top < 60) st.scrollIntoView({ behavior: reduce ? "auto" : "smooth", block: "start" });
    if (n === 3) loadSlots();
    if (n === 4) renderSummary();
  }
  function done(n, text) {
    var s = $('.bk-step[data-step="' + n + '"]', bk);
    s.classList.add("is-done"); $('[data-sum="' + n + '"]', bk).textContent = text;
  }
  function undone(from) {
    for (var n = from; n <= 4; n++) {
      var s = $('.bk-step[data-step="' + n + '"]', bk);
      if (s) { s.classList.remove("is-done"); $('[data-sum="' + n + '"]', bk).textContent = ""; }
    }
  }
  function selectSvc(k, silent) {
    S.svc = k; S.size = null; S.day = null; S.slot = null; S.slots = null;
    if (k !== "ceramic") S.tier = null;
    $$("[data-svc]", bk).forEach(function (b) { b.setAttribute("aria-checked", String(b.dataset.svc === k)); });
    var tiers = $("[data-tiers]", bk);
    tiers.hidden = k !== "ceramic";
    $$("[data-tier]", bk).forEach(function (c) { c.setAttribute("aria-pressed", String(+c.dataset.tier === S.tier)); });
    renderSizes(); undone(2);
    if (k === "ceramic" && S.tier == null) { undone(1); return; }
    done(1, svcName());
    if (!silent) openStep(2);
  }
  function renderSizes() {
    var box = $("[data-sizes]", bk); if (!box) return;
    box.innerHTML = sizeLabels().map(function (l, i) {
      var p = null;
      if (S.svc === "ceramic") p = S.tier == null ? GS.ceramic.prices[i][0] : GS.ceramic.prices[i][S.tier];
      else if (S.svc) p = pkg(S.svc).prices[i];
      return '<button type="button" class="opt" role="radio" aria-checked="' + (S.size === i) + '" data-size="' + i + '"><b>' + l + '</b><em>' + (p ? money(p) : "") + '</em></button>';
    }).join("");
    $("[data-twostep]", bk).hidden = S.svc !== "lux";
    renderPrice();
  }
  function renderPrice() {
    var el = $("[data-price]", bk), p = price();
    el.hidden = p == null;
    if (p != null) el.innerHTML = "<span>" + svcName() + " · " + sizeLabels()[S.size] + "</span><b>" + money(p) + "</b>";
  }
  function loadSlots() {
    var days = $("[data-days]", bk), times = $("[data-times]", bk), msg = $("[data-slot-msg]", bk);
    if (S.slots) return renderDays();
    days.innerHTML = ""; times.innerHTML = ""; msg.textContent = "Loading open times…";
    fetch("/api/ghl-free-slots", {
      method: "POST", headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ calendarId: GS.calendarId, dateISO: chicagoISODate(new Date()), durationHours: hours() })
    }).then(function (r) { if (!r.ok) throw new Error(r.status); return r.json(); })
      .then(function (data) {
        S.slots = {};
        Object.keys(data).filter(function (k) { return /^\d{4}-\d{2}-\d{2}$/.test(k); }).sort().forEach(function (k) {
          var s = (data[k] && data[k].slots) || [];
          if (s.length) S.slots[k] = s;
        });
        renderDays();
      })
      .catch(function () {
        S.slots = null;
        msg.innerHTML = 'Couldn\'t load times right now. <a href="tel:' + GS.tel + '">Call</a> or <a href="sms:' + GS.tel + '">text</a> ' + GS.phone + " and we'll get you in.";
      });
  }
  function renderDays() {
    var days = $("[data-days]", bk), msg = $("[data-slot-msg]", bk);
    var keys = Object.keys(S.slots || {}).slice(0, 14);
    if (!keys.length) { msg.innerHTML = 'No open times online in the next two weeks. <a href="tel:' + GS.tel + '">Call</a> or <a href="sms:' + GS.tel + '">text</a> ' + GS.phone + "."; return; }
    msg.textContent = "Times shown in Central Time.";
    days.innerHTML = keys.map(function (k) {
      return '<button type="button" class="chip day" aria-pressed="' + (S.day === k) + '" data-day="' + k + '"><small>' + fmtDay(k) + "</small>" + (+k.slice(8)) + "</button>";
    }).join("");
    if (!S.day) S.day = keys[0];
    $$("[data-day]", bk).forEach(function (b) { b.setAttribute("aria-pressed", String(b.dataset.day === S.day)); });
    renderTimes();
  }
  function renderTimes() {
    var times = $("[data-times]", bk);
    var list = (S.slots && S.slots[S.day]) || [];
    times.innerHTML = list.map(function (iso) {
      return '<button type="button" class="chip" aria-pressed="' + (S.slot === iso) + '" data-slot="' + iso + '">' + fmtTime(iso) + "</button>";
    }).join("");
  }
  function renderSummary() {
    var p = price();
    $("[data-summary]", bk).innerHTML = "<b>" + svcName() + "</b> · " + (S.size != null ? sizeLabels()[S.size] : "") +
      (p != null ? " · <b>" + money(p) + "</b>" : "") + (S.slot ? "<br>" + fmtDay(S.day, "long") + " at " + fmtTime(S.slot) : "") +
      "<br>Drop off at 606 N. Country Fair Dr, Champaign, IL.";
  }

  if (bk) {
    bk.addEventListener("click", function (e) {
      var t;
      if ((t = e.target.closest("[data-svc]"))) return selectSvc(t.dataset.svc);
      if ((t = e.target.closest("[data-tier]"))) {
        S.tier = +t.dataset.tier;
        $$("[data-tier]", bk).forEach(function (c) { c.setAttribute("aria-pressed", String(c === t)); });
        S.size = null; S.slots = null; renderSizes(); undone(2); done(1, svcName()); return openStep(2);
      }
      if ((t = e.target.closest("[data-size]"))) {
        S.size = +t.dataset.size; S.slots = null; S.day = null; S.slot = null;
        renderSizes(); undone(3); done(2, sizeLabels()[S.size] + " · " + money(price()));
        return setTimeout(function () { openStep(3); }, reduce ? 0 : 350);
      }
      if ((t = e.target.closest("[data-day]"))) {
        S.day = t.dataset.day; S.slot = null;
        $$("[data-day]", bk).forEach(function (b) { b.setAttribute("aria-pressed", String(b === t)); });
        return renderTimes();
      }
      if ((t = e.target.closest("[data-slot]"))) {
        S.slot = t.dataset.slot;
        $$("[data-slot]", bk).forEach(function (b) { b.setAttribute("aria-pressed", String(b === t)); });
        done(3, fmtDay(S.day) + " " + fmtTime(S.slot));
        return openStep(4);
      }
      if ((t = e.target.closest("[data-goto]"))) {
        var n = +t.dataset.goto, st = t.parentNode;
        if (n === 1 || st.classList.contains("is-done")) openStep(n);
      }
    });
    var ts = $("[data-twostep] input", bk);
    if (ts) ts.addEventListener("change", function () {
      S.twoStep = ts.checked; renderPrice();
      if (S.size != null) done(2, sizeLabels()[S.size] + " · " + money(price()));
      done(1, svcName());
    });
    bk.addEventListener("submit", function (e) {
      e.preventDefault();
      var msg = $(".form-msg", bk), f = bk.elements;
      var name = f.name.value.trim(), phone = f.phone.value.trim();
      if (!S.svc || S.size == null || (S.svc === "ceramic" && S.tier == null)) { openStep(!S.svc ? 1 : 2); return; }
      if (!S.slot) { openStep(3); return; }
      if (!name || phone.replace(/\D/g, "").length < 10) { msg.className = "form-msg err"; msg.textContent = "Add your name and a 10-digit phone number."; (name ? f.phone : f.name).focus(); return; }
      var btn = $("button[type=submit]", bk); btn.disabled = true; msg.className = "form-msg"; msg.textContent = "Booking…";
      fetch("/api/ghl-create-booking", {
        method: "POST", headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          calendarId: GS.calendarId, startISO: S.slot, durationHours: hours(),
          name: name, phone: phone, email: f.email.value.trim(),
          service: S.svc === "ceramic" ? "Ceramic Coating" : "Car Detailing", packageName: svcName(),
          vehicle: sizeLabels()[S.size], vehicleInfo: f.vehicleInfo.value.trim(), notes: f.notes.value.trim(),
          price: price(), textMe: f.textMe.checked, page: location.pathname
        })
      }).then(function (r) { return r.json().then(function (j) { if (!r.ok) throw j; return j; }); })
        .then(function () {
          bk.outerHTML = '<div class="bk-done"><h3>You\'re booked, ' + name.split(" ")[0].replace(/[<>&"]/g, "") + "!</h3><p>" + svcName() + " · " + fmtDay(S.day, "long") + " at " + fmtTime(S.slot) +
            '</p><p class="muted">Drop off at 606 N. Country Fair Dr, Champaign, IL. Questions? <a href="tel:' + GS.tel + '">Call</a> or <a href="sms:' + GS.tel + '">text</a> ' + GS.phone + ".</p></div>";
        })
        .catch(function () {
          btn.disabled = false; msg.className = "form-msg err";
          msg.innerHTML = 'That didn\'t go through. <a href="tel:' + GS.tel + '">Call</a> or <a href="sms:' + GS.tel + '">text</a> ' + GS.phone + " and we'll book you.";
        });
    });
    renderSizes();
  }

  // "Book" buttons preselect a service, then the link scrolls to #book.
  document.addEventListener("click", function (e) {
    var b = e.target.closest("[data-book]");
    if (b && bk && b.dataset.book) {
      var k = b.dataset.book;
      if (k === "ceramic") { S.tier = S.tier == null ? 0 : S.tier; $$("[data-tier]", bk).forEach(function (c) { c.setAttribute("aria-pressed", String(+c.dataset.tier === S.tier)); }); }
      selectSvc(k, true); openStep(k === "ceramic" ? 1 : 2);
    }
    var q = e.target.closest("[data-quote]");
    if (q) { var sel = $("[data-quote-form] select[name=service]"); if (sel) sel.value = q.dataset.quote; }
  });

  // ── quote form (photos are shrunk in the browser before upload) ──
  var qf = $("[data-quote-form]");
  function shrink(file) {
    return new Promise(function (res) {
      var img = new Image(), u = URL.createObjectURL(file);
      img.onload = function () {
        var m = 1600, w = img.naturalWidth, h = img.naturalHeight, s = Math.min(1, m / Math.max(w, h));
        var c = document.createElement("canvas"); c.width = Math.round(w * s); c.height = Math.round(h * s);
        c.getContext("2d").drawImage(img, 0, 0, c.width, c.height); URL.revokeObjectURL(u);
        res(c.toDataURL("image/jpeg", 0.78));
      };
      img.onerror = function () { URL.revokeObjectURL(u); res(null); };
      img.src = u;
    });
  }
  if (qf) {
    var fi = qf.elements.photos, fl = $("[data-file-label]", qf);
    fi.addEventListener("change", function () { var n = fi.files.length; fl.textContent = n ? n + " photo" + (n > 1 ? "s" : "") + " added" + (n > 3 ? " (first 3 sent)" : "") : "Add photos (optional)"; });
    qf.addEventListener("submit", function (e) {
      e.preventDefault();
      var f = qf.elements, msg = $(".form-msg", qf), btn = $("button[type=submit]", qf);
      if (!f.name.value.trim() || f.phone.value.replace(/\D/g, "").length < 10 || !f.vehicle.value.trim()) {
        msg.className = "form-msg err"; msg.textContent = "Add your name, a 10-digit phone and your vehicle."; return;
      }
      btn.disabled = true; msg.className = "form-msg"; msg.textContent = "Sending…";
      Promise.all(Array.prototype.slice.call(fi.files, 0, 3).map(shrink)).then(function (photos) {
        return fetch("/api/ghl-quote", {
          method: "POST", headers: { "Content-Type": "application/json" },
          body: JSON.stringify({ service: f.service.value, name: f.name.value.trim(), phone: f.phone.value.trim(), vehicle: f.vehicle.value.trim(), textMe: f.textMe.checked, notes: f.notes.value.trim(), photos: photos.filter(Boolean), page: location.pathname })
        });
      }).then(function (r) { if (!r.ok) throw r; return r.json(); })
        .then(function () {
          qf.reset(); fl.textContent = "Add photos (optional)"; btn.disabled = false;
          msg.className = "form-msg ok"; msg.textContent = (f.textMe.checked ? "Got it! We'll text you a quote soon." : "Got it! We'll call you with a quote soon.");
        })
        .catch(function () {
          btn.disabled = false; msg.className = "form-msg err";
          msg.innerHTML = 'That didn\'t send. <a href="sms:' + GS.tel + '">Text</a> your photos to ' + GS.phone + " instead.";
        });
    });
  }

  // ── price calculator ──
  var calc = $("[data-calc]");
  if (calc) {
    var cs = $("[data-calc-svc]", calc), cz = $("[data-calc-size]", calc), c2 = $("[data-calc-twostep]", calc), cp = $("[data-calc-price]", calc), cb = $("[data-calc-book]", calc);
    var upd = function () {
      var v = cs.value, i = +cz.value, p;
      var labels = v.indexOf("ceramic") === 0 ? GS.ceramicSizes : GS.sizes;
      $$("option", cz).forEach(function (o, k) { o.textContent = labels[k]; });
      if (v.indexOf("ceramic") === 0) p = GS.ceramic.prices[i][+v.split(":")[1]];
      else { var k = pkg(v); p = k.prices[i] + (v === "lux" && $("input", c2).checked ? k.twoStepAdd : 0); }
      c2.hidden = v !== "lux"; cp.textContent = money(p);
    };
    [cs, cz, $("input", c2)].forEach(function (el) { el.addEventListener("change", upd); }); upd();
    cb.addEventListener("click", function () {
      if (!bk) return;
      var v = cs.value;
      if (v.indexOf("ceramic") === 0) { S.tier = +v.split(":")[1]; $$("[data-tier]", bk).forEach(function (c) { c.setAttribute("aria-pressed", String(+c.dataset.tier === S.tier)); }); selectSvc("ceramic", true); }
      else selectSvc(v, true);
      if (v === "lux") { S.twoStep = $("input", c2).checked; var t2 = $("[data-twostep] input", bk); if (t2) t2.checked = S.twoStep; }
      S.size = +cz.value; renderSizes(); done(1, svcName()); done(2, sizeLabels()[S.size] + " · " + money(price())); openStep(3);
    });
  }

  // ── GHL chat bubble: desktop only, after idle. Never on phones (no pop-ups). ──
  if (GS.chatWidgetId && window.innerWidth >= 1020 && !saveData) {
    window.addEventListener("load", function () {
      setTimeout(function () {
        var d = document.createElement("div"); d.setAttribute("data-chat-widget", ""); d.setAttribute("data-widget-id", GS.chatWidgetId); document.body.appendChild(d);
        var s = document.createElement("script"); s.src = "https://beta.leadconnectorhq.com/loader.js";
        s.setAttribute("data-resources-url", "https://beta.leadconnectorhq.com/chat-widget/loader.js"); s.setAttribute("data-widget-id", GS.chatWidgetId);
        document.body.appendChild(s);
      }, 5000);
    });
  }
})();
`;
}
