// Browser script → output/assets/site.js. The booking widget and price
// calculator are in site/booking.js (→ output/assets/book.js).
export function clientJS(data) {
  return `/* The Gloss Spot — generated by site/build.js. Edit site/client.js. */
window.GS = ${JSON.stringify(data)};
` + String.raw`
(function () {
  "use strict";
  var GS = window.GS;
  var $ = function (s, r) { return (r || document).querySelector(s); };
  var $$ = function (s, r) { return Array.prototype.slice.call((r || document).querySelectorAll(s)); };
  var reduce = window.matchMedia && matchMedia("(prefers-reduced-motion: reduce)").matches;
  var saveData = navigator.connection && (navigator.connection.saveData || /2g/.test(navigator.connection.effectiveType || ""));

  // ── header + drawer ──
  var hdr = $("[data-hdr]");
  var onScroll = function () { if (hdr) hdr.classList.toggle("solid", window.scrollY > 40); };
  window.addEventListener("scroll", onScroll, { passive: true }); onScroll();
  var mb = $("[data-menu]"), dr = $("[data-drawer]");
  if (mb && dr) {
    mb.addEventListener("click", function () {
      var open = dr.hasAttribute("hidden");
      if (open) dr.removeAttribute("hidden"); else dr.setAttribute("hidden", "");
      mb.setAttribute("aria-expanded", String(open));
      hdr.classList.add("solid");
    });
    dr.addEventListener("click", function (e) { if (e.target.closest("a")) { dr.setAttribute("hidden", ""); mb.setAttribute("aria-expanded", "false"); } });
  }

  // ── reveal on scroll ──
  var reveals = $$(".reveal");
  if ("IntersectionObserver" in window && !reduce) {
    var ro = new IntersectionObserver(function (es) {
      es.forEach(function (e) { if (e.isIntersecting) { e.target.classList.add("in"); ro.unobserve(e.target); } });
    }, { rootMargin: "0px 0px -8% 0px" });
    reveals.forEach(function (el) { ro.observe(el); });
  } else reveals.forEach(function (el) { el.classList.add("in"); });

  // ── background videos (OpenArt loops from our real photos) ──
  function startVideo(v) {
    var mobile = window.innerWidth < 760;
    var src = (mobile && v.dataset.srcMobile) || v.dataset.src;
    if (!src || v.dataset.loaded) return;
    v.dataset.loaded = "1";
    v.src = src;
    v.addEventListener("playing", function () { v.classList.add("on"); }, { once: true });
    var p = v.play(); if (p && p.catch) p.catch(function () {});
  }
  var vids = $$("video[data-src]");
  if (!reduce && !saveData && vids.length) {
    var hv = vids.filter(function (v) { return v.classList.contains("bgv-hero"); });
    var rest = vids.filter(function (v) { return !v.classList.contains("bgv-hero"); });
    // Hero video only after the page (and its photo) has fully loaded.
    var afterLoad = function () { setTimeout(function () { hv.forEach(startVideo); }, 600); };
    if (document.readyState === "complete") afterLoad(); else window.addEventListener("load", afterLoad);
    if ("IntersectionObserver" in window) {
      var vo = new IntersectionObserver(function (es) {
        es.forEach(function (e) {
          var v = e.target;
          if (e.isIntersecting) { startVideo(v); if (v.paused && v.dataset.loaded) v.play().catch(function () {}); }
          else if (!v.paused) v.pause();
        });
      }, { rootMargin: "200px" });
      rest.forEach(function (v) { vo.observe(v); });
    }
  }

  // ── Instagram embeds: load Instagram's script only when the grid is near ──
  var ig = $("[data-ig]");
  if (ig) {
    var loadIg = function () {
      if (window.instgrm) return window.instgrm.Embeds.process();
      var s = document.createElement("script"); s.async = true; s.src = "https://www.instagram.com/embed.js"; document.body.appendChild(s);
    };
    if ("IntersectionObserver" in window) {
      var io = new IntersectionObserver(function (es) { if (es[0].isIntersecting) { io.disconnect(); loadIg(); } }, { rootMargin: "600px" });
      io.observe(ig);
    } else loadIg();
  }

  // ── before/after sliders ──
  $$(".ba-range").forEach(function (r) {
    r.addEventListener("input", function () { r.parentNode.style.setProperty("--pos", r.value + "%"); });
  });

  // ── "Get a Quote" buttons preselect the service in the quote form ──
  // (Booking buttons and the booking widget live in book.js.)
  var qf = $("[data-quote-form]");
  function syncCoverage() {
    var c = qf && $("[data-coverage]", qf), sel = qf && qf.elements.service;
    if (c && sel) c.hidden = sel.value !== "Paint Protection Film";
  }
  document.addEventListener("click", function (e) {
    var q = e.target.closest("[data-quote]");
    if (q && qf && qf.elements.service && qf.elements.service.tagName === "SELECT") { qf.elements.service.value = q.dataset.quote; syncCoverage(); }
  });

  // ── quote form (photos are shrunk in the browser before upload) ──
  function shrink(file) {
    return new Promise(function (res) {
      var img = new Image(), u = URL.createObjectURL(file);
      img.onload = function () {
        var m = 1600, w = img.naturalWidth, h = img.naturalHeight, s = Math.min(1, m / Math.max(w, h));
        var c = document.createElement("canvas"); c.width = Math.round(w * s); c.height = Math.round(h * s);
        c.getContext("2d").drawImage(img, 0, 0, c.width, c.height); URL.revokeObjectURL(u);
        res(c.toDataURL("image/jpeg", 0.78));
      };
      img.onerror = function () { URL.revokeObjectURL(u); res(null); };
      img.src = u;
    });
  }
  if (qf) {
    var fi = qf.elements.photos, fl = $("[data-file-label]", qf);
    if (qf.elements.service.tagName === "SELECT") qf.elements.service.addEventListener("change", syncCoverage);
    syncCoverage();
    fi.addEventListener("change", function () { var n = fi.files.length; fl.textContent = n ? n + " photo" + (n > 1 ? "s" : "") + " added" + (n > 3 ? " (first 3 sent)" : "") : "Add photos (optional)"; });
    qf.addEventListener("submit", function (e) {
      e.preventDefault();
      var f = qf.elements, msg = $(".form-msg", qf), btn = $("button[type=submit]", qf);
      if (!f.name.value.trim() || f.phone.value.replace(/\D/g, "").length < 10 || !f.vehicle.value.trim()) {
        msg.className = "form-msg err"; msg.textContent = "Add your vehicle, name and a 10-digit phone."; return;
      }
      btn.disabled = true; msg.className = "form-msg"; msg.textContent = "Sending…";
      var ppfQuote = f.service.value === "Paint Protection Film";
      Promise.all(Array.prototype.slice.call(fi.files, 0, 3).map(shrink)).then(function (photos) {
        return fetch("/api/ghl-quote", {
          method: "POST", headers: { "Content-Type": "application/json" },
          body: JSON.stringify({ service: f.service.value, coverage: ppfQuote ? f.coverage.value : "", name: f.name.value.trim(), phone: f.phone.value.trim(), email: f.email.value.trim(), vehicle: f.vehicle.value.trim(), textMe: f.textMe.checked, smsConsent: f.textMe.checked, notes: f.notes.value.trim(), photos: photos.filter(Boolean), page: location.pathname })
        });
      }).then(function (r) { if (!r.ok) throw r; return r.json(); })
        .then(function (j) {
          var text = f.textMe.checked;
          qf.reset(); syncCoverage(); fl.textContent = "Add photos (optional)"; btn.disabled = false;
          msg.className = "form-msg ok";
          msg.textContent = j.confirmed === false ? "Got it! We'll text you to confirm. Questions? Call " + GS.phone + "." : (text ? "Got it! We'll text you a quote soon." : "Got it! We'll call you with a quote soon.");
        })
        .catch(function () {
          btn.disabled = false; msg.className = "form-msg err";
          msg.innerHTML = 'That didn\'t send. <a href="sms:' + GS.tel + '">Text</a> your photos to ' + GS.phone + " instead.";
        });
    });
  }

  // ── GHL chat bubble: desktop only, after idle. Never on phones (no pop-ups). ──
  if (GS.chatWidgetId && window.innerWidth >= 1020 && !saveData) {
    window.addEventListener("load", function () {
      setTimeout(function () {
        var d = document.createElement("div"); d.setAttribute("data-chat-widget", ""); d.setAttribute("data-widget-id", GS.chatWidgetId); document.body.appendChild(d);
        var s = document.createElement("script"); s.src = "https://beta.leadconnectorhq.com/loader.js";
        s.setAttribute("data-resources-url", "https://beta.leadconnectorhq.com/chat-widget/loader.js"); s.setAttribute("data-widget-id", GS.chatWidgetId);
        document.body.appendChild(s);
      }, 5000);
    });
  }
})();
`;
}
